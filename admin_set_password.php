<?php
// Sets the admin username and password. Run from the terminal only:
//   on this computer:  /Applications/MAMP/bin/php/php8.3.28/bin/php admin_set_password.php
//   on hosting (SSH):  php admin_set_password.php
// The password is stored only as a hash, outside the web root.

if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

require __DIR__ . '/admin_auth.php';

echo 'Admin username: ';
$username = trim((string) fgets(STDIN));

echo 'New password (min 10 characters, hidden): ';
system('stty -echo');
$password = trim((string) fgets(STDIN));
system('stty echo');
echo "\n";

if ($username === '' || strlen($password) < 10) {
    fwrite(STDERR, "Username is required and the password must be at least 10 characters.\n");
    exit(1);
}

$config = "<?php\n// HoneyArt admin login (generated by admin_set_password.php)\nreturn " . var_export([
    'username' => $username,
    'password_hash' => password_hash($password, PASSWORD_DEFAULT),
], true) . ";\n";

if (file_put_contents(ADMIN_CONFIG_PATH, $config) === false) {
    fwrite(STDERR, 'Could not write ' . ADMIN_CONFIG_PATH . "\n");
    exit(1);
}
chmod(ADMIN_CONFIG_PATH, 0600);

echo 'Saved to ' . ADMIN_CONFIG_PATH . "\n";
